import Foundation

/// In-app localization, English default. Nine languages: the string table is
/// the only place they live, and `s()` falls back to English for any key a
/// translation is missing, so a partial language degrades instead of breaking.
/// Mirrors the language picker behaviour of the web prototype.
enum L {
    static let languages: [(code: String, label: String)] = [
        ("en", "English"), ("ko", "한국어"), ("ja", "日本語"),
        ("es", "Español"), ("pt", "Português"), ("de", "Deutsch"),
        ("fr", "Français"), ("it", "Italiano"), ("zh-Hans", "简体中文"),
    ]

    /// Picks the in-app language from the device on first launch only.
    ///
    /// The table has nine languages but `@AppStorage("rc_lang")` defaulted to
    /// English for everyone, so a Korean or Japanese user — the first markets
    /// for this app — met an English onboarding and had to find the globe
    /// before anything read naturally. Runs once: after that the stored value
    /// is the user's own choice and must not be overwritten.
    static func seedLanguageFromDevice() {
        let key = "rc_lang"
        guard UserDefaults.standard.string(forKey: key) == nil else { return }
        let codes = languages.map(\.code)
        // The raw device order, not `Locale.preferredLanguages`, which resolves
        // against the bundle's declared localizations and would collapse to the
        // development language on a build that declared none.
        let device = UserDefaults.standard.stringArray(forKey: "AppleLanguages")
            ?? Locale.preferredLanguages
        for preferred in device {
            // "zh-Hans-CN" -> "zh-Hans", "pt-BR" -> "pt", "de-DE" -> "de"
            if let exact = codes.first(where: { preferred.hasPrefix($0) }) {
                UserDefaults.standard.set(exact, forKey: key)
                return
            }
            let base = preferred.split(separator: "-").first.map(String.init) ?? preferred
            if let match = codes.first(where: { $0 == base }) {
                UserDefaults.standard.set(match, forKey: key)
                return
            }
        }
    }

    static func locale(_ lang: String) -> Locale {
        Locale(identifier: ["en": "en_US", "ko": "ko_KR", "ja": "ja_JP",
                            "es": "es_ES", "pt": "pt_BR", "de": "de_DE",
                            "fr": "fr_FR", "it": "it_IT", "zh-Hans": "zh_CN"][lang] ?? "en_US")
    }

    private static var formatters: [String: DateFormatter] = [:]

    /// Date + time in the language the user picked in-app, not the system locale.
    static func dateTime(_ date: Date, _ lang: String) -> String {
        formatter(lang, template: "MMMdjmm").string(from: date)
    }

    static func dateOnly(_ date: Date, _ lang: String) -> String {
        formatter(lang, template: "MMMdEEE").string(from: date)
    }

    private static func formatter(_ lang: String, template: String) -> DateFormatter {
        let key = lang + "|" + template
        if let f = formatters[key] { return f }
        let f = DateFormatter()
        f.locale = locale(lang)
        f.setLocalizedDateFormatFromTemplate(template)
        formatters[key] = f
        return f
    }

    /// Korean postpositions depend on whether the previous syllable ends in a
    /// consonant, so "%@는" is wrong half the time. Picks 은/는 for `word`.
    static func topicParticle(after word: String, _ lang: String) -> String {
        guard lang == "ko", let last = word.unicodeScalars.last else { return "" }
        let value = last.value
        guard (0xAC00...0xD7A3).contains(value) else { return "는" }
        let hasFinalConsonant = (value - 0xAC00) % 28 != 0
        return hasFinalConsonant ? "은" : "는"
    }

    /// "Smart crop needs a pass", with the right Korean particle.
    static func locked(_ feature: String, _ lang: String) -> String {
        if lang == "ko" {
            return feature + topicParticle(after: feature, lang) + " 패스가 필요합니다"
        }
        return String(format: s("locked_fmt", lang), feature)
    }

    static func s(_ key: String, _ lang: String) -> String {
        table[lang]?[key] ?? table["en"]?[key] ?? key
    }

